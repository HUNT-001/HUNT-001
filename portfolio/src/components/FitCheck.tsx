"use client";
import Link from "next/link";
import { useState } from "react";
import type { FitResult } from "@/lib/fit";

const SAMPLE = `Edge AI / ML Systems Engineer (Intern)
We're looking for someone to optimize and deploy deep learning models on embedded and FPGA targets.
- Quantize models (INT8/INT4) and profile latency on edge hardware
- Work with Xilinx/AMD Vitis AI, HLS and Vivado flows
- Write Python and C++; familiarity with PyTorch and ONNX/OpenVINO
- Bonus: RTL experience in SystemVerilog, verification with UVM or cocotb
- Bonus: experience building LLM agents or RAG pipelines`;

export default function FitCheck() {
  const [jd, setJd] = useState("");
  const [busy, setBusy] = useState(false);
  const [res, setRes] = useState<FitResult | null>(null);
  const [err, setErr] = useState("");
  const [copied, setCopied] = useState(false);

  async function run() {
    if (busy) return;
    setErr(""); setBusy(true); setRes(null); setCopied(false);
    try {
      const r = await fetch("/api/fit", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jd }) });
      const data = await r.json();
      if (!r.ok) setErr(data?.error ?? "Something went wrong."); else setRes(data as FitResult);
    } catch { setErr("Couldn't reach the analyser — try again in a moment."); }
    setBusy(false);
  }

  const R = 52, C = 2 * Math.PI * R;
  const color = !res ? "#38bdf8" : res.score >= 80 ? "#22c55e" : res.score >= 62 ? "#38bdf8" : res.score >= 45 ? "#bc7b3a" : "#f472b6";

  return (
    <div className="demo fit">
      <div className="demo-top">
        <span>// JOB-FIT CHECK · paste a job description</span>
        <span className="src" style={{ color: res?.mode === "ai" ? "#a78bfa" : "#7fa6d4" }}>
          {res ? (res.mode === "ai" ? `AI · ${res.provider}` : "offline matcher") : "ready"}
        </span>
      </div>

      <div className="fit-in">
        <textarea value={jd} onChange={(e) => setJd(e.target.value)} maxLength={7000}
          placeholder="Paste the role description here — requirements, nice-to-haves, the lot." rows={7} />
        <div className="fit-actions">
          <button className="play" onClick={run} disabled={busy || jd.trim().length < 40}>
            {busy ? "Analysing…" : "Check fit →"}
          </button>
          <button className="ghostbtn" onClick={() => { setJd(SAMPLE); setRes(null); }}>Use a sample JD</button>
          <span className="fit-hint">{jd.length}/7000 · nothing is stored</span>
        </div>
        {err && <p className="fit-err">{err}</p>}
      </div>

      {busy && <div className="fit-scan"><i /><span>Reading requirements · matching against projects · checking gaps…</span></div>}

      {res && (
        <div className="fit-out">
          <div className="fit-score">
            <svg viewBox="0 0 130 130" width="130" height="130">
              <circle cx="65" cy="65" r={R} fill="none" stroke="#16203a" strokeWidth="10" />
              <circle cx="65" cy="65" r={R} fill="none" stroke={color} strokeWidth="10" strokeLinecap="round"
                strokeDasharray={C} strokeDashoffset={C * (1 - res.score / 100)} transform="rotate(-90 65 65)" className="fit-arc" />
              <text x="65" y="66" textAnchor="middle" fontSize="32" fontWeight="800" fill="#eaf2ff">{res.score}</text>
              <text x="65" y="86" textAnchor="middle" fontSize="10" fill="#7f98bd" fontFamily="var(--font-mono)">/ 100</text>
            </svg>
            <div>
              <div className="fit-verdict" style={{ color }}>{res.verdict}</div>
              <p className="fit-pitch">{res.pitch}</p>
              <button className="ghostbtn" onClick={() => { navigator.clipboard?.writeText(res.pitch); setCopied(true); }}>
                {copied ? "Copied ✓" : "Copy summary"}
              </button>
            </div>
          </div>

          <div className="fit-cols">
            <div>
              <h4>Where he matches</h4>
              <ul className="fit-list ok">
                {res.matches.map((m, i) => (
                  <li key={i} style={{ animationDelay: `${i * 70}ms` }}>
                    <b>{m.requirement}</b>
                    <span>{m.evidence}</span>
                    {m.href && <Link href={m.href}>See evidence →</Link>}
                  </li>
                ))}
              </ul>
            </div>
            <div>
              <h4>Honest gaps</h4>
              {res.gaps.length ? (
                <ul className="fit-list gap">
                  {res.gaps.map((g, i) => <li key={i} style={{ animationDelay: `${i * 70}ms` }}><span>{g}</span></li>)}
                </ul>
              ) : <p className="fit-none">No obvious gaps against this description.</p>}
            </div>
          </div>
          <p className="fit-foot">
            {res.mode === "ai"
              ? "Generated by an LLM grounded only in Tanush's real résumé facts — it's an aid, not a verdict."
              : "Keyword matcher running offline (no AI key configured or quota reached) — a rougher estimate."}
          </p>
        </div>
      )}
    </div>
  );
}
